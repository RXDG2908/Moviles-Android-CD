import androidx.compose.ui.unit.dp
import androidx.lifecycle.compose.collectAsStateWithLifecycle
import com.tecsup.campusgps.model.UbicacionUi
import com.tecsup.campusgps.viewmodel.MapaViewModel

@OptIn(ExperimentalMaterial3Api::class)
@Composable
fun PantallaMapa(vm: MapaViewModel) {
    val estado by vm.estado.collectAsStateWithLifecycle()

    // TODO Paso 2: lanzador de permisos con
    // rememberLauncherForActivityResult(ActivityResultContracts.RequestMultiplePermissions())

    fun alPulsar() {
        // TODO Paso 2: ¿ya tienes FINE o COARSE? -> vm.buscar()
        // TODO Paso 2: si no -> lanzador.launch(arrayOf(FINE, COARSE))
        vm.buscar()
    }

    Scaffold(
        topBar = {
            TopAppBar(
                title = { Text("CampusGPS") },
                colors = TopAppBarDefaults.topAppBarColors(
                    containerColor = MaterialTheme.colorScheme.primary,
                    titleContentColor = MaterialTheme.colorScheme.onPrimary
                )
            )
        }
    ) { padding ->
        Column(
            modifier = Modifier
                .fillMaxSize()
                .padding(padding)
                .padding(16.dp),
            horizontalAlignment = Alignment.CenterHorizontally,
            verticalArrangement = Arrangement.spacedBy(12.dp)
        ) {
            Button(
                onClick = { alPulsar() },
                enabled = estado !is UbicacionUi.Buscando
            ) {
                Text("Obtener mi ubicación")
            }

            // TODO Paso 3: MapaUbicacion(..., modifier = Modifier.weight(1f))

            when (val e = estado) {
                UbicacionUi.Inicial -> Text("Pulsa el botón para ver dónde estás")
                UbicacionUi.Buscando -> CircularProgressIndicator()
                is UbicacionUi.Lista -> {
                    Text("Latitud: ${e.posicion.latitud}")
                    Text("Longitud: ${e.posicion.longitud}")
                }
                is UbicacionUi.Error -> Text(
                    text = e.mensaje,
                    color = MaterialTheme.colorScheme.error
                )
            }
        }
    }
}
